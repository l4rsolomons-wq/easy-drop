import { useState } from "react";
import { Donut, HBars, LineChart } from "@/components/charts";
import { Icon } from "@/components/Icon";
import {
  Badge, Banner, Button, Card, CardHeader, EmptyState, KeyValue, PageHeader, Progress, Row, SimTag, Stat,
  StatusBadge, Tabs, TableWrap, Td, Th,
} from "@/components/ui";
import { IncidentModal, InspectionModal, NearMissModal } from "@/components/workflow/FleetWorkflows";
import { dateSA, num, pct, time24 } from "@/lib/format";
import { useRouter } from "@/router";
import { useStore } from "@/state/store";
