/* ====================== SAFETY DASHBOARD ====================== */

export function SafetyPage() {
  const { state } = useStore();
  const { navigate } = useRouter();
  const [incidentOpen, setIncidentOpen] = useState(false);
  const [nearMissOpen, setNearMissOpen] = useState(false);

  const todayIncidents = state.incidents.filter((i) => i.date === state.today);
  const preventable = state.incidents.filter((i) => i.preventable).length;
  const inspectedToday = state.inspections.filter((i) => i.date === state.today).length;
  const inspectionCompliance = (inspectedToday / state.vehicles.length) * 100;
  const trainingTotal = state.drivers.length * state.drivers[0].training.length;
  const trainingDone = state.drivers.reduce((s, d) => s + d.training.filter((t) => t.status === "Completed").length, 0);
  const trainingCompliance = (trainingDone / trainingTotal) * 100;

  return (
    <>
      <PageHeader
        title="Safety Dashboard"
        description="Incidents, near misses, inspection compliance, training and simulated driving events across the fleet."
        actions={
          <>
            <Button variant="secondary" icon="eye" onClick={() => setNearMissOpen(true)}>Report near miss</Button>
            <Button variant="danger" icon="shield" onClick={() => setIncidentOpen(true)}>Report incident</Button>
          </>
        }
      />

      <div className="grid grid-cols-2 gap-3 md:grid-cols-3 lg:grid-cols-6">
        <Stat label="Incidents today" value={todayIncidents.length} tone={todayIncidents.length ? "critical" : "success"} icon="alert" onClick={() => navigate("/ops/incidents")} />
        <Stat label="Open incidents" value={state.incidents.filter((i) => i.status !== "Closed").length} tone="warning" icon="folder" onClick={() => navigate("/ops/incidents")} />
        <Stat label="Preventable (all time)" value={preventable} tone={preventable ? "warning" : "success"} sub="target: zero" icon="target" />
        <Stat label="Near misses logged" value={state.nearMisses.length} icon="eye" onClick={() => navigate("/ops/near-misses")} />
        <Stat label="Inspection compliance" value={pct(inspectionCompliance)} tone={inspectionCompliance >= 95 ? "success" : "warning"} icon="clipboard" onClick={() => navigate("/ops/inspections")} />
        <Stat label="Training compliance" value={pct(trainingCompliance)} tone={trainingCompliance >= 90 ? "success" : "warning"} icon="graduation" onClick={() => navigate("/ops/training")} />
      </div>

      <div className="mt-4 grid gap-4 lg:grid-cols-3">
        <Card>
          <CardHeader title="Incidents by severity" subtitle="All recorded incidents" icon="alert" />
          <div className="p-4">
            <Donut
              segments={["Low", "Medium", "High", "Critical"].map((s, i) => ({
                label: s,
                value: state.incidents.filter((x) => x.severity === s).length,
                colour: ["#12a05c", "#d97706", "#dc2626", "#7f1d1d"][i],
              }))}
              centreValue={String(state.incidents.length)}
              centreLabel="incidents"
            />
          </div>
        </Card>
        <Card>
          <CardHeader title="Near misses by risk type" subtitle="Reporting is blame-free and encouraged" icon="eye" />
          <div className="p-4">
            <HBars
              data={Array.from(new Set(state.nearMisses.map((n) => n.riskType))).map((t) => ({
                label: t,
                value: state.nearMisses.filter((n) => n.riskType === t).length,
              }))}
              colour="#2b5480"
            />
          </div>
        </Card>
        <Card>
          <CardHeader title="Safety events trend" subtitle="Daily incidents over 30 days" icon="activity" />
          <div className="p-4">
            <LineChart data={state.history.map((h) => ({ label: h.date.slice(8), value: h.incidents }))} height={170} colour="#dc2626" yMin={0} yMax={3} />
          </div>
        </Card>
      </div>

      <div className="mt-4 grid gap-4 lg:grid-cols-2">
        <Card>
          <CardHeader
            title="Simulated telematics events"
            subtitle="Speed, braking and acceleration events generated by the demo"
            icon="signal"
            action={<SimTag />}
          />
          <TableWrap>
            <thead><tr><Th>Vehicle</Th><Th>Event</Th><Th>Value</Th><Th>Location</Th><Th>Time</Th></tr></thead>
            <tbody>
              {state.telematics.slice(0, 10).map((t) => (
                <Row key={t.id}>
                  <Td className="font-semibold text-navy-950">{t.vehicleId}</Td>
                  <Td><Badge tone={t.type === "Speeding" || t.type === "Harsh Braking" ? "warning" : "neutral"}>{t.type}</Badge></Td>
                  <Td className="num">{t.value}</Td>
                  <Td>{t.location}</Td>
                  <Td className="num">{time24(t.time)}</Td>
                </Row>
              ))}
            </tbody>
          </TableWrap>
        </Card>
        <Card>
          <CardHeader title="Corrective actions" subtitle="What is being done about recorded incidents" icon="clipboard" />
          <ul className="divide-y divide-mist-100">
            {state.incidents.map((i) => (
              <li key={i.id} className="px-4 py-3">
                <div className="flex flex-wrap items-center justify-between gap-2">
                  <button onClick={() => navigate(`/ops/incidents?id=${i.id}`)} className="text-[13px] font-semibold text-navy-950 hover:underline">
                    {i.id} · {i.type}
                  </button>
                  <StatusBadge status={i.status} />
                </div>
                <p className="mt-1 text-[12.5px] text-charcoal-500">{i.correctiveAction || "Corrective action still to be captured."}</p>
              </li>
            ))}
          </ul>
        </Card>
      </div>

      <IncidentModal open={incidentOpen} onClose={() => setIncidentOpen(false)} />
      <NearMissModal open={nearMissOpen} onClose={() => setNearMissOpen(false)} />
    </>
  );
}

/* ====================== INCIDENTS ====================== */

export function IncidentsPage() {
  const { state } = useStore();
  const { params, setParam } = useRouter();
  const [open, setOpen] = useState(false);
  const [tab, setTab] = useState("All");
  const selected = state.incidents.find((i) => i.id === params.get("id"));
  const list = state.incidents.filter((i) => tab === "All" || i.status === tab);

  return (
    <>
      <PageHeader
        title="Incidents"
        description="Every safety incident recorded against a driver, vehicle or delivery, with severity and corrective action."
        actions={<Button variant="danger" icon="shield" onClick={() => setOpen(true)}>Report incident</Button>}
      />
      {selected && (
        <div className="mb-4">
          <Card>
            <CardHeader
              title={`${selected.id} · ${selected.type}`}
              subtitle={`${dateSA(selected.date)} ${selected.time} · ${selected.location}`}
              icon="alert"
              action={
                <>
                  <Badge tone={selected.severity === "High" || selected.severity === "Critical" ? "critical" : "warning"}>{selected.severity}</Badge>
                  <StatusBadge status={selected.status} />
                  <Button size="sm" variant="ghost" icon="x" onClick={() => setParam("id", null)}>Close</Button>
                </>
              }
            />
            <div className="grid gap-4 p-4 lg:grid-cols-2">
              <KeyValue
                cols={1}
                items={[
                  ["Driver", state.drivers.find((d) => d.id === selected.driverId)?.name ?? "—"],
                  ["Vehicle", selected.vehicleId ?? "—"],
                  ["Delivery", selected.deliveryId ?? "—"],
                  ["Preventable", selected.preventable ? "Yes" : "No"],
                ]}
              />
              <div className="space-y-3">
                <div>
                  <p className="text-[11.5px] font-bold uppercase tracking-wide text-charcoal-400">Description</p>
                  <p className="mt-1 text-[13.5px] text-charcoal-700">{selected.description}</p>
                </div>
                <div>
                  <p className="text-[11.5px] font-bold uppercase tracking-wide text-charcoal-400">Corrective action</p>
                  <p className="mt-1 text-[13.5px] text-charcoal-700">{selected.correctiveAction || "Not captured yet."}</p>
                </div>
              </div>
            </div>
          </Card>
        </div>
      )}
      <Card>
        <Tabs className="px-3" tabs={["All", "Open", "Under Review", "Closed"].map((t) => ({ key: t, label: t, count: t === "All" ? state.incidents.length : state.incidents.filter((i) => i.status === t).length }))} active={tab} onChange={setTab} />
        <TableWrap>
          <thead><tr><Th>Incident</Th><Th>Type</Th><Th>Date</Th><Th>Time</Th><Th className="hidden md:table-cell">Location</Th><Th className="hidden lg:table-cell">Driver</Th><Th>Vehicle</Th><Th>Severity</Th><Th>Status</Th></tr></thead>
          <tbody>
            {list.map((i) => (
              <Row key={i.id} onClick={() => setParam("id", i.id)}>
                <Td className="font-semibold text-navy-950">{i.id}</Td>
                <Td>{i.type}</Td>
                <Td>{dateSA(i.date)}</Td>
                <Td className="num">{i.time}</Td>
                <Td className="hidden max-w-[200px] truncate md:table-cell">{i.location}</Td>
                <Td className="hidden lg:table-cell">{state.drivers.find((d) => d.id === i.driverId)?.name ?? "—"}</Td>
                <Td>{i.vehicleId ?? "—"}</Td>
                <Td><Badge tone={i.severity === "High" || i.severity === "Critical" ? "critical" : i.severity === "Medium" ? "warning" : "neutral"}>{i.severity}</Badge></Td>
                <Td><StatusBadge status={i.status} /></Td>
              </Row>
            ))}
          </tbody>
        </TableWrap>
        {!list.length && <EmptyState icon="shield" title="No incidents with this status" />}
      </Card>
      <IncidentModal open={open} onClose={() => setOpen(false)} />
    </>
  );
}

