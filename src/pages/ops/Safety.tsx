/* ====================== INSPECTIONS ====================== */

export function InspectionsPage() {
  const { state } = useStore();
  const [inspectId, setInspectId] = useState<string | null>(null);
  const today = state.inspections.filter((i) => i.date === state.today);
  const pass = today.filter((i) => i.result === "Pass").length;
  const notInspected = state.vehicles.filter((v) => !today.some((i) => i.vehicleId === v.id));

  return (
    <>
      <PageHeader
        title="Vehicle Inspections"
        description="A 13-point check runs before every shift. A failed critical item blocks the vehicle from dispatch until it is resolved."
      />
      <div className="grid grid-cols-2 gap-3 lg:grid-cols-4">
        <Stat label="Inspections today" value={today.length} icon="clipboard" />
        <Stat label="Passed" value={pass} tone="success" icon="check" />
        <Stat label="Failed" value={today.length - pass} tone={today.length - pass ? "critical" : "success"} icon="warning" />
        <Stat label="Not yet inspected" value={notInspected.length} tone={notInspected.length ? "warning" : "success"} icon="clock" />
      </div>

      {notInspected.length > 0 && (
        <Card className="mt-4">
          <CardHeader title="Vehicles still to inspect today" subtitle="Run the pre-shift check before dispatching these vehicles" icon="warning" />
          <ul className="divide-y divide-mist-100">
            {notInspected.map((v) => (
              <li key={v.id} className="flex items-center gap-3 px-4 py-2.5">
                <span className="w-20 text-[13px] font-bold text-navy-950">{v.id}</span>
                <span className="flex-1 truncate text-[12.5px] text-charcoal-400">{v.model} · {v.registration}</span>
                <StatusBadge status={v.status} />
                <Button size="xs" variant="primary" icon="clipboard" onClick={() => setInspectId(v.id)}>Inspect now</Button>
              </li>
            ))}
          </ul>
        </Card>
      )}

      <Card className="mt-4">
        <CardHeader title="Inspection records" subtitle="Most recent first" icon="list" />
        <ul className="divide-y divide-mist-100">
          {state.inspections.slice(0, 12).map((i) => {
            const failed = i.items.filter((x) => x.result === "Fail");
            return (
              <li key={i.id} className="px-4 py-3">
                <div className="flex flex-wrap items-center justify-between gap-2">
                  <div>
                    <p className="text-[13.5px] font-semibold text-navy-950">
                      {i.vehicleId} · {dateSA(i.date)} {i.time}
                    </p>
                    <p className="text-[12px] text-charcoal-400">
                      {state.drivers.find((d) => d.id === i.driverId)?.name ?? i.driverId} · odometer {num(i.odometer)} km
                    </p>
                  </div>
                  <div className="flex items-center gap-2">
                    {i.criticalFail && <Badge tone="critical">Critical failure</Badge>}
                    <StatusBadge status={i.result} />
                  </div>
                </div>
                <div className="mt-2 flex flex-wrap gap-1">
                  {i.items.map((it) => (
                    <span
                      key={it.name}
                      className={cn(
                        "rounded border px-1.5 py-0.5 text-[10.5px] font-semibold",
                        it.result === "Pass" ? "border-mist-200 bg-mist-50 text-charcoal-500" : "border-red-200 bg-red-50 text-red-700",
                      )}
                      title={it.notes}
                    >
                      {it.name} {it.result === "Fail" ? "✕" : "✓"}
                    </span>
                  ))}
                </div>
                {failed.length > 0 && (
                  <p className="mt-2 text-[12.5px] text-red-700">
                    <Icon name="warning" className="mr-1 inline h-3.5 w-3.5" />
                    Failed: {failed.map((f) => f.name).join(", ")}
                  </p>
                )}
              </li>
            );
          })}
        </ul>
      </Card>

      <Card className="mt-4">
        <CardHeader title="Inspection compliance by vehicle" subtitle="Share of vehicles inspected today" icon="target" />
        <div className="p-4">
          <Progress value={(today.length / state.vehicles.length) * 100} />
          <p className="mt-2 text-[12.5px] text-charcoal-400">
            {today.length} of {state.vehicles.length} vehicles inspected today.
          </p>
        </div>
      </Card>

      <InspectionModal vehicleId={inspectId} open={!!inspectId} onClose={() => setInspectId(null)} />
    </>
  );
}
